use super::NativeCurrency;
use alloy::primitives::{Address, address};
use std::time::Duration;

pub(super) struct EvmPreset {
    pub name: &'static str,
    pub native_currency: NativeCurrency,
    pub rpc_endpoints: Vec<String>,
    pub explorer_urls: &'static [&'static str],
    pub multicall: Option<Address>,
    pub wrapped_native: Option<Address>,
    pub native_usd_oracle: Option<Address>,
    pub block_time: Duration,
    pub finality_depth: u64,
}

impl EvmPreset {
    pub(super) fn for_chain(chain_id: u64) -> Option<Self> {
        PRESETS
            .iter()
            .find(|spec| spec.chain_id == chain_id)
            .map(PresetSpec::to_preset)
    }
}

struct PresetSpec {
    chain_id: u64,
    name: &'static str,
    currency_name: &'static str,
    currency_symbol: &'static str,
    currency_decimals: u8,
    rpc_endpoints: &'static [&'static str],
    explorer_urls: &'static [&'static str],
    multicall: Option<Address>,
    native_usd_oracle: Option<Address>,
    block_time: Duration,
    finality_depth: u64,
}

impl PresetSpec {
    fn to_preset(&self) -> EvmPreset {
        EvmPreset {
            name: self.name,
            native_currency: NativeCurrency {
                name: self.currency_name.into(),
                symbol: self.currency_symbol.into(),
                decimals: self.currency_decimals,
            },
            rpc_endpoints: self
                .rpc_endpoints
                .iter()
                .map(|&url| url.to_owned())
                .collect(),
            explorer_urls: self.explorer_urls,
            multicall: self.multicall,
            wrapped_native: crate::amounts::wrapped_native_token_for_chain(self.chain_id),
            native_usd_oracle: self.native_usd_oracle,
            block_time: self.block_time,
            finality_depth: self.finality_depth,
        }
    }
}

